# Reads and writes the generated Luau index of the item icon atlases (src/shared/Data/ItemIconAtlas.luau, S35/S52).
# Standard library only (no Pillow): build_final.py (SVG icons, Playwright) and import_png.py (PNG icons, Pillow)
# share it. An index entry is {"accent": "#RRGGBB" | None, "layers": [{"sheet", "x", "y", "layer"}]} with layer
# "m" (tier tint), "b" (fixed colours) or "a" (accent), the same shape render.render() returns.
import re
import shutil
import subprocess

T = {"m": "tier", "a": "accent", "b": None}
T_BACK = {"tier": "m", "accent": "a", None: "b"}

HEADER = [
    "--!strict",
    "-- GENERATED by tools/icons/build_final.py (ICONS, SVG) and tools/icons/import_png.py (PNG). Do not edit by hand:",
    "-- change the generators and rebuild.",
    "-- Item icon atlases (art/icons/items_<n>.png, 1024x1024, 128 px cells). An icon is 1-3 stacked layers,",
    "-- drawn in list order:",
    '--   t = "tier"   greyscale material, ImageColor3 = TIER_TINT[def.tier]',
    '--   t = "accent" greyscale accent, ImageColor3 = accent colour (element, potion, ore, scroll seal, ...)',
    "--   t = nil      fixed colours, ImageColor3 = white",
    "-- Sheets 1..SVG_SHEETS hold ICONS (drawn by code); later sheets hold PNG (pictures from art/icons/src, S52), which",
    "-- the game prefers once their sheets are loaded and otherwise falls back to ICONS (Logic/ItemIcons).",
    "-- Sheet asset ids live in Data/ItemIconSheets.luau (filled in by hand after upload).",
    "",
    'export type Layer = { s: number, x: number, y: number, t: ("tier" | "accent")? }',
    "export type Icon = { accent: string?, layers: { Layer } }",
    "",
]

ENTRY = re.compile(r'\["([^"]+)"\]\s*=\s*\{')
LAYER = re.compile(r'\{\s*s\s*=\s*(\d+),\s*x\s*=\s*(\d+),\s*y\s*=\s*(\d+)(?:,\s*t\s*=\s*"(\w+)")?\s*\}')
ACCENT = re.compile(r'accent\s*=\s*"(#[0-9A-Fa-f]{6})"')
TINT = re.compile(r'\[(\d+)\]\s*=\s*"(#[0-9A-Fa-f]{6})",\s*--\s*(.+)')


def _block(text, name):
    """Body of `local <name>: ... = { ... }` (between the outer braces), or "" when the table is missing."""
    m = re.search(r"local " + name + r"\b[^=]*=\s*\{", text)
    if not m:
        return ""
    depth, i = 1, m.end()
    while depth:
        c = text[i]
        depth += c == "{"
        depth -= c == "}"
        i += 1
    return text[m.end():i - 1]


def _entries(body):
    out = {}
    pos = 0
    while True:
        m = ENTRY.search(body, pos)
        if not m:
            return out
        depth, i = 1, m.end()
        while depth:
            c = body[i]
            depth += c == "{"
            depth -= c == "}"
            i += 1
        inner = body[m.end():i - 1]
        acc = ACCENT.search(inner)
        layers = [{"sheet": int(s), "x": int(x), "y": int(y), "layer": T_BACK[t or None]}
                  for s, x, y, t in LAYER.findall(inner)]
        out[m.group(1)] = {"accent": acc.group(1) if acc else None, "layers": layers}
        pos = i


def parse(path):
    """The index as a dict: cell, sheets, svg_sheets, tiers [(t, colour, name)], icons, png (insertion ordered)."""
    text = open(path, encoding="utf-8").read()
    num = lambda k, d=None: int(re.search(k + r"\s*=\s*(\d+)", text).group(1)) if re.search(k + r"\s*=\s*(\d+)", text) else d
    sheets = num(r"\bSHEETS")
    return {
        "cell": num(r"\bCELL"),
        "sheets": sheets,
        "svg_sheets": num(r"\bSVG_SHEETS", sheets),
        "tiers": [(int(t), c, n.strip()) for t, c, n in TINT.findall(_block(text, "TIER_TINT"))],
        "icons": _entries(_block(text, "ICONS")),
        "png": _entries(_block(text, "PNG")),
    }


def _entry_line(key, e):
    parts = []
    for L in e["layers"]:
        t = T[L["layer"]]
        parts.append(f'{{ s = {L["sheet"]}, x = {L["x"]}, y = {L["y"]}' + (f', t = "{t}"' if t else "") + " }")
    acc = f'accent = "{e["accent"].upper()}", ' if e.get("accent") else ""
    return f'\t["{key}"] = {{ {acc}layers = {{ {", ".join(parts)} }} }},'


def render_text(cell, tiers, icons, svg_sheets, png=None, sheets=None):
    """Luau source of the index (before StyLua). `icons` and `png` are ordered dicts key -> entry."""
    png = png or {}
    total = max([svg_sheets] + [L["sheet"] for e in png.values() for L in e["layers"]]) if sheets is None else sheets
    lines = list(HEADER) + ["local TIER_TINT: { [number]: string } = {"]
    for t, c, name in tiers:
        lines.append(f'\t[{t}] = "{c.upper()}", -- {name}')
    lines += ["}", "", "local ICONS: { [string]: Icon } = {"]
    lines += [_entry_line(k, e) for k, e in icons.items()]
    lines += ["}", "", "-- Pictures from art/icons/src (tools/icons/import_png.py), sorted by key.",
              "local PNG: { [string]: Icon } = {"]
    lines += [_entry_line(k, e) for k, e in png.items()]
    lines += ["}", "", "return table.freeze({", f"\tCELL = {cell},", f"\tSHEETS = {total},", f"\tSVG_SHEETS = {svg_sheets},",
              "\tTIER_TINT = table.freeze(TIER_TINT),", "\tICONS = ICONS,", "\tPNG = PNG,", "})", ""]
    return "\n".join(lines)


def write(path, text, format=True):
    """Writes the index; formats it with StyLua when it is on PATH (rokit), else prints a reminder."""
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    if not format:
        return
    stylua = shutil.which("stylua")
    if stylua:
        subprocess.check_call([stylua, path])
    else:
        print(f"Uwaga: brak stylua w PATH, uruchom `stylua {path}` przed commitem.")
